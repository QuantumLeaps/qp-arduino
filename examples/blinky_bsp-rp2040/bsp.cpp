#ifndef QP_ARDUINO_QS_SERIAL
#define QP_ARDUINO_QS_SERIAL Serial
#endif
#ifndef QP_ARDUINO_QS_HOST_WAIT_MS
#define QP_ARDUINO_QS_HOST_WAIT_MS 5000U
#endif

