void QF::onCleanup() {
}
//............................................................................
void QV::onIdle() { // called with interrupts DISABLED, see NOTE in qv.hpp
#ifdef QS_ON
    QF_INT_ENABLE(); // re-enable interrupts before touching the transport

    // QS transmit
    qsWriteBounded(0U); // never wait here; the idle loop comes back soon

    // QS receive (bench profile: QSPY/QUTest can talk back over the same port)
    int avail = QP_ARDUINO_QS_SERIAL.available();
    if (avail > 0) {
        do {
            QS::rxPut(static_cast<std::uint8_t>(QP_ARDUINO_QS_SERIAL.read()));
        } while (--avail > 0);
        QS::rxParse();
    }
#else
    // Sleep until the next interrupt; QV_CPU_SLEEP() re-enables interrupts
    // atomically with WFI on ARMv6-M. USB is serviced from an interrupt on
    // this core, so it keeps working.
    QV_CPU_SLEEP();
#endif
}
//............................................................................
extern "C" Q_NORETURN Q_onError(char const * const module, int const id) {
#ifdef QS_ON
    // Try to get the assertion record out while interrupts may still be
    // running; QS::onFlush() below is bounded so this cannot hang.
    QS_ASSERTION(module, id, 0U);
#else
    Q_UNUSED_PAR(module);
    Q_UNUSED_PAR(id);
#endif
    __asm volatile ("cpsid i" ::: "memory"); // disable interrupts directly

    // Distinct analyzer signature: LED solid on for two seconds, tick probe
    // silent, then a watchdog reset so the fixture recovers on its own (it has
    // no reset button and no SWD).
    digitalWrite(kLedPin, HIGH);
    std::uint32_t const start = micros();
    while ((micros() - start) < 2000000U) {
    }
    watchdog_reboot(0U, 0U, 10U);
    for (;;) {
    }
}

//----------------------------------------------------------------------------
// QS callbacks (always defined; see the note above)
bool QS::onStartup(void const *arg) {
    Q_UNUSED_PAR(arg);
    static std::uint8_t qsTxBuf[2048]; // QS transmit buffer
    static std::uint8_t qsRxBuf[128];  // QS receive buffer
    initBuf(qsTxBuf, sizeof(qsTxBuf));
    rxInitBuf(qsRxBuf, sizeof(qsRxBuf));
    QP_ARDUINO_QS_SERIAL.begin(115200); // baud rate is ignored by USB CDC
    return true;
}
