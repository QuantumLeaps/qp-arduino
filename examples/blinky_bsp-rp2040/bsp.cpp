//----------------------------------------------------------------------------
// QF callbacks
void QF::onStartup() {
    // interrupts are configured and started here, after the AOs are started
    bool const ok = add_repeating_timer_us(
        -static_cast<int64_t>(1000000 / BSP::TICKS_PER_SEC),
        tickCallback, nullptr, &l_tickTimer);
    Q_ASSERT_ID(100, ok);
}
